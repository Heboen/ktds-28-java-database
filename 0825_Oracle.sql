-- 42. 모든 사원들의 현재 직무명과 과거의 직무명을 조회한다. 만약 직무가 한번도 변경되지 않았다면, 과거의 직무명은 '없음' 으로 조회한다.
SELECT J.JOB_TITLE
	 , NVL(JH.JOB_TITLE, '없음') 
  FROM EMPLOYEES E
 INNER JOIN JOBS J
 	ON E.JOB_ID = J.JOB_ID
  LEFT OUTER JOIN (SELECT J.JOB_TITLE 
 				  , JH.EMPLOYEE_ID 
			   FROM JOB_HISTORY JH
			  INNER JOIN JOBS J
				 ON JH.JOB_ID = J.JOB_ID) JH
	ON E.EMPLOYEE_ID = JH.EMPLOYEE_ID 
;
-- 43. 직무가 변경될 때마다 급여가 15%씩 감소한다고 했을 때, 직무가 변경된 사원들의 감소된 급여를 조회한다.
SELECT E.EMPLOYEE_ID 
	 , E.FIRST_NAME 
	 , SALARY - (SALARY * 0.15)*JH.J_CHANGED_CNT AS REDUCED_SAL
  FROM EMPLOYEES E
 INNER JOIN (SELECT E.EMPLOYEE_ID 
				 , COUNT(E.EMPLOYEE_ID ) AS J_CHANGED_CNT
			  FROM EMPLOYEES E
			 INNER JOIN JOB_HISTORY JH 
				ON E.EMPLOYEE_ID = JH.EMPLOYEE_ID 
			 GROUP BY E.EMPLOYEE_ID ) JH
 	ON E.EMPLOYEE_ID = JH.EMPLOYEE_ID 			 
;
