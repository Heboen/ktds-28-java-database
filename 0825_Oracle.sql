SELECT (SALARY * 0.1) * SERVICE_YEAR AS BONUS
	 , EMPLOYEE_ID
	 , SALARY
  FROM (SELECT EMPLOYEE_ID
			 , SALARY
			 , TO_NUMBER(TO_CHAR(SYSDATE, 'YYYY')) - TO_NUMBER(TO_CHAR(HIRE_DATE, 'YYYY')) AS SERVICE_YEAR
		  FROM EMPLOYEES)
;
