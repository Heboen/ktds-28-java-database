WITH DATES AS (
	SELECT MAX(HIRE_DATE) AS MAX_HIRE_DATE
		 , MIN(HIRE_DATE) AS MIN_HIRE_DATE
	  FROM EMPLOYEES
)
SELECT EMPLOYEE_ID
	 , HIRE_DATE
	 , CASE HIRE_DATE
	 		WHEN MAX_HIRE_DATE THEN '신규 사원'
	 		WHEN MIN_HIRE_DATE THEN '원년 사원'
	 		ELSE '사원'
	   END AS "입사 순서"
  FROM EMPLOYEES ,DATES
;
-- CROSS JOIN (데이터를 조건 상관 없이 모든 ROW에 다 같다 붙이는 조인)
SELECT EMPLOYEE_ID
	 , HIRE_DATE
	 , CASE HIRE_DATE
