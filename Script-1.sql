WITH TMP AS (
SELECT 'Y' AS FLAG
  FROM DUAL
 UNION
SELECT 'N'
  FROM DUAL
 UNION
SELECT 'R'
  FROM DUAL
 UNION
SELECT NULL
  FROM DUAL
)
-- TMP테이블의 FLAG 컬럼의 값이 'Y' 라면 "On" 으로 조회하고, 'R'이라면 "Ready'로 조회하고, 아니라면 "Off"로 조회한다.
-- NULL 이라면 Error를 조회한다.
SELECT FLAG 
	 , CASE 
	 		WHEN FLAG = 'Y' THEN
	 			'On'
	 		WHEN FLAG = 'R' THEN
	 			'Ready'
	 		WHEN FLAG IS NULL THEN
	 			'Error'
	 		ELSE
	 			'Off'
	 	END AS ON_OFF 
  FROM TMP
;

