	 	 	ELSE '사원'
	   END AS "입사 순서"
  FROM EMPLOYEES
 CROSS JOIN (SELECT MAX(HIRE_DATE) AS MAX_HIRE_DATE
 				  , MIN(HIRE_DATE) AS MIN_HIRE_DATE
 			   FROM EMPLOYEES) DATES
